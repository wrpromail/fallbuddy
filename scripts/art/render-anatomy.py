"""Render aligned FallBuddy anatomy plates from the Écorché GLB in Blender 4.3."""

import json
import re
import sys
from pathlib import Path

import bpy
from bpy_extras.object_utils import world_to_camera_view
from mathutils import Vector


def bounds(obj):
    points = [obj.matrix_world @ Vector(point) for point in obj.bound_box]
    return tuple(Vector([extreme(p[i] for p in points) for i in range(3)]) for extreme in (min, max))


def center(obj):
    low, high = bounds(obj)
    return (low + high) / 2


model_file, target_dir = map(Path, sys.argv[sys.argv.index("--") + 1:])
target_dir.mkdir(parents=True, exist_ok=True)

bpy.ops.wm.read_factory_settings(use_empty=True)
bpy.ops.import_scene.gltf(filepath=str(model_file.resolve()))
meshes = [obj for obj in bpy.context.scene.objects if obj.type == "MESH"]
by_name = {obj.name.lower(): obj for obj in meshes}
bones = [obj for obj in meshes if obj.get("layer") == "skeleton" and obj.get("tissue") != "eye"]
superficial = [obj for obj in meshes if obj.get("layer") == "superficial muscles"]
for side in ("left", "right"):
    assert len([obj for obj in bones if re.fullmatch(side + r" \w+ rib", obj.name.lower())]) == 12

scene = bpy.context.scene
scene.render.engine = "BLENDER_WORKBENCH"
scene.render.resolution_x = 600
scene.render.resolution_y = 900
scene.render.resolution_percentage = 100
scene.render.film_transparent = True
scene.render.image_settings.file_format = "PNG"
scene.render.image_settings.color_mode = "RGBA"
scene.view_settings.view_transform = "Standard"
shading = scene.display.shading
shading.light = "STUDIO"
shading.color_type = "VERTEX"
shading.show_shadows = False
shading.show_cavity = True
shading.cavity_type = "WORLD"
shading.cavity_ridge_factor = 1.1
shading.cavity_valley_factor = 1.0

camera_data = bpy.data.cameras.new("Orthographic camera")
camera_data.type = "ORTHO"
camera = bpy.data.objects.new("Orthographic camera", camera_data)
scene.collection.objects.link(camera)
scene.camera = camera

floor = min(bounds(obj)[0].z for obj in bones)
crown = max(bounds(obj)[1].z for obj in bones)
height = crown - floor
middle = Vector((0, 0, (crown + floor) / 2))
camera_data.ortho_scale = height * 1.08

targets = {
    "head": center(by_name["frontal bone"]),
    "back": Vector((0, 0, floor + height * 0.75)),
    "waist": Vector((0, 0, floor + height * 0.60)),
    "tailbone": Vector((0, 0, floor + height * 0.53)),
}
for side in ("left", "right"):
    suffix = side[0]
    _, shoulder_high = bounds(by_name[f"{side} humerus"])
    wrist_low, wrist_high = bounds(by_name[f"{side} radius"])
    ankle_low, ankle_high = bounds(by_name[f"{side} tibia"])
    targets[f"shoulder_{suffix}"] = Vector((*center(by_name[f"{side} humerus"])[:2], shoulder_high.z - height * 0.014))
    targets[f"wrist_{suffix}"] = Vector((wrist_low.x if side == "right" else wrist_high.x, 0, wrist_low.z))
    targets[f"knee_{suffix}"] = center(by_name[f"{side} patella"])
    targets[f"ankle_{suffix}"] = Vector((*((ankle_low + ankle_high) / 2)[:2], ankle_low.z + height * 0.012))

anchors = {}
for view, direction in (("front", -1), ("back", 1)):
    camera.location = middle + Vector((0, direction * 4, 0))
    camera.rotation_euler = (middle - camera.location).to_track_quat("-Z", "Y").to_euler()
    bpy.context.view_layer.update()
    anchors[view] = {}
    for part, target in targets.items():
        point = world_to_camera_view(scene, camera, target)
        if view == "front" and part in {"back", "tailbone"}:
            continue
        anchors[view][part] = [round(100 * point.x, 1), round(100 * (1 - point.y), 1)]
    for layer, shown in (("bones", bones), ("muscles", superficial)):
        shown_names = {obj.name for obj in shown}
        for obj in meshes:
            obj.hide_render = obj.name not in shown_names
        scene.render.filepath = str(target_dir.resolve() / f"{layer}-{view}.png")
        bpy.ops.render.render(write_still=True)

coordinates = json.dumps(anchors, indent=2)
(target_dir / "anatomy-anchors.generated.ts").write_text(
    "// Generated by scripts/art/render-anatomy.py. Coordinates are percentages of each plate.\n"
    + "export const ANATOMY_ANCHORS = " + coordinates + " as const;\n"
)
